import AppKit

/// Hangs text copied to the clipboard. Each copy is saved as a note in
/// Pinza's own folder, so on the line it behaves like any other note.
///
/// Off until the user turns it on. The pasteboard has no change notification,
/// so its change count is checked twice a second; what was copied is only read
/// once its types say it is text and nothing private.
@MainActor
final class ClipboardWatcher {
    private let onText: (URL) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// The last text saved. Some apps put the same text on the clipboard
    /// again; it hangs once, unless it has been taken down since.
    private var last: (text: String, url: URL)?

    private static let enabledKey = "clipboardEnabled"

    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// Copies that carry text but are not a note. A file copied in Finder
    /// brings its name, and a note copied from the line is already on it.
    /// Password managers and similar apps mark private or temporary copies,
    /// following nspasteboard.org.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL, Line.ownType,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init(onText: @escaping (URL) -> Void) {
        self.onText = onText
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, items.count == 1,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }),
              let text = pb.string(forType: .string),
              text.count <= Notes.maxCharacters,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              pb.changeCount == count else { return }
        save(text)
    }

    private func save(_ text: String) {
        if let last, last.text == text, FileManager.default.fileExists(atPath: last.url.path) { return }
        guard let url = Notes.create(text, prefix: "Clipboard") else { return }
        last = (text, url)
        onText(url)
    }
}
