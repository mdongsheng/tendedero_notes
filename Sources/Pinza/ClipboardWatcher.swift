import AppKit

/// Hangs whatever is copied: text becomes a text note, an image a PNG, and
/// files copied in Finder hang where they are. See Intake.
///
/// Off until the user turns it on. The pasteboard has no change notification,
/// so its change count is checked twice a second; what was copied is only read
/// once its types say it is nothing private.
@MainActor
final class ClipboardWatcher {
    private let onNote: (URL) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// The last copy hung. Some apps put the same thing on the clipboard
    /// again; it hangs once, unless it has been taken down since.
    private var last: (signature: String, urls: [URL])?

    private static let enabledKey = "clipboardEnabled"

    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// A note copied from the line is already on it. Password managers and
    /// similar apps mark private or temporary copies, following
    /// nspasteboard.org.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        Line.ownType,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init(onNote: @escaping (URL) -> Void) {
        self.onNote = onNote
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }) else { return }
        let signature = Self.signature(of: pb)
        if let last, last.signature == signature,
           last.urls.allSatisfy({ FileManager.default.fileExists(atPath: $0.path) }) { return }
        let urls = Intake.notes(from: pb, prefix: "Clipboard")
        guard !urls.isEmpty else { return }
        last = (signature, urls)
        urls.forEach(onNote)
    }

    private static func signature(of pb: NSPasteboard) -> String {
        let files = (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL])?
            .map(\.path).joined(separator: "\n") ?? ""
        let image = (pb.data(forType: .png) ?? pb.data(forType: .tiff))?.hashValue ?? 0
        return "\(files)|\(pb.string(forType: .string) ?? "")|\(image)"
    }
}
