import AppKit
import Carbon

/// The sheet a note is written on, just under the line: the same paper the
/// note hangs as, in the same glass frame. ⌘↩ hangs it, or saves a note
/// that is already on the line; Escape puts the sheet away.
///
/// Anything can be pasted or dropped on it besides words: a screenshot
/// just copied, a picture, a file from Finder. A note that carries one is
/// saved as a rich text document with it inside; one with only words stays
/// a plain text file.
///
/// Opened for a new note, it offers what was copied in the last few
/// minutes, so a screenshot or a passage just copied is one click away.
///
/// It floats without bringing Pinza to the front, the way Spotlight does,
/// so the app you were in keeps its menu bar and gets the keyboard back as
/// soon as the sheet goes.
@MainActor
final class NoteEditor: NSObject, NSWindowDelegate, NSTextViewDelegate {
    static let shared = NoteEditor()

    /// A new note was written: its file, and where its sheet was on screen,
    /// so it can fly from there to the line.
    var onCreated: (URL, CGRect) -> Void = { _, _ in }
    /// A note on the line was edited and written back.
    var onSaved: (URL) -> Void = { _ in }
    /// A note on the line was edited into a new file: a text note that now
    /// carries a picture or a file becomes a rich one.
    var onReplaced: (URL, URL) -> Void = { _, _ in }

    private var window: EditorPanel?
    private var textView: NoteTextView?
    private var paperView: NSView?
    private var offerView: NSView?
    private var paperTop: NSLayoutConstraint?
    /// The note being edited, or nil for a new one.
    private var editing: URL?
    /// A new note put away unfinished waits here for next time.
    private var draft = NSAttributedString()

    var isOpen: Bool { window != nil }

    func new() {
        if let window, editing == nil {
            window.makeKeyAndOrderFront(nil)
            return
        }
        show(draft, editing: nil)
        offerClipboard()
    }

    func edit(_ url: URL) {
        let text: NSAttributedString
        if Notes.isRich(url), let rich = Notes.readRich(url) {
            text = rich
        } else if let plain = Notes.read(url) {
            text = NSAttributedString(string: plain)
        } else {
            NSWorkspace.shared.open(url)
            return
        }
        show(text, editing: url)
    }

    // MARK: What was just copied

    /// How recent a copy must be to be offered.
    private static let recent: TimeInterval = 10 * 60

    private var clipboardCount = NSPasteboard.general.changeCount
    /// When the clipboard last changed, as far as Pinza saw. What was there
    /// before it launched counts as old.
    private var clipboardChanged = Date.distantPast
    /// A copy is offered once: asked about and declined, it is not asked
    /// about again.
    private var offeredCount: Int?
    private var clipboardTimer: Timer?

    /// The pasteboard has no change notification, so its change count is
    /// checked every second, which costs next to nothing.
    func watchClipboard() {
        guard clipboardTimer == nil else { return }
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.noteClipboardChange() }
        }
        RunLoop.main.add(timer, forMode: .common)
        clipboardTimer = timer
    }

    private func noteClipboardChange() {
        let count = NSPasteboard.general.changeCount
        guard count != clipboardCount else { return }
        clipboardCount = count
        clipboardChanged = Date()
    }

    /// Private copies, as password managers mark them, and notes copied off
    /// the line are not offered.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        Line.ownType,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private func offerClipboard() {
        noteClipboardChange()
        let pb = NSPasteboard.general
        guard offeredCount != clipboardCount,
              Date().timeIntervalSince(clipboardChanged) <= Self.recent,
              let items = pb.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }),
              let preview = ClipboardPreview(pb) else { return }
        offeredCount = clipboardCount
        showOffer(preview)
    }

    private func showOffer(_ preview: ClipboardPreview) {
        guard let window, let glass = window.contentView, let paperView else { return }
        let icon = NSImageView(image: preview.icon)
        icon.imageScaling = .scaleProportionallyUpOrDown
        icon.wantsLayer = true
        icon.layer?.cornerRadius = 4
        icon.layer?.masksToBounds = true
        let title = NSTextField(labelWithString: L("Use what you just copied?"))
        title.font = .systemFont(ofSize: 12, weight: .semibold)
        let detail = NSTextField(labelWithString: preview.summary)
        detail.font = .systemFont(ofSize: 11)
        detail.textColor = .secondaryLabelColor
        detail.lineBreakMode = .byTruncatingTail
        detail.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)
        let words = NSStackView(views: [title, detail])
        words.orientation = .vertical
        words.alignment = .leading
        words.spacing = 1
        words.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)
        let use = NSButton(title: L("Use"), target: self, action: #selector(useClipboard))
        use.bezelStyle = .rounded
        use.controlSize = .small
        let dismiss = NSButton(image: NSImage(systemSymbolName: "xmark", accessibilityDescription: L("Not now"))!,
                               target: self, action: #selector(dismissOffer))
        dismiss.isBordered = false
        dismiss.toolTip = L("Not now")
        let row = NSStackView(views: [icon, words, use, dismiss])
        row.orientation = .horizontal
        row.spacing = 8
        row.edgeInsets = NSEdgeInsets(top: 6, left: 8, bottom: 6, right: 6)
        row.wantsLayer = true
        row.layer?.cornerRadius = 10
        row.layer?.cornerCurve = .continuous
        row.layer?.backgroundColor = NSColor.labelColor.withAlphaComponent(0.06).cgColor
        row.translatesAutoresizingMaskIntoConstraints = false
        glass.addSubview(row)

        paperTop?.isActive = false
        let top = paperView.topAnchor.constraint(equalTo: row.bottomAnchor, constant: 6)
        NSLayoutConstraint.activate([
            icon.widthAnchor.constraint(equalToConstant: 28),
            icon.heightAnchor.constraint(equalToConstant: 28),
            row.topAnchor.constraint(equalTo: glass.topAnchor, constant: 30),
            row.leadingAnchor.constraint(equalTo: glass.leadingAnchor, constant: 8),
            row.trailingAnchor.constraint(equalTo: glass.trailingAnchor, constant: -8),
            top,
        ])
        paperTop = top
        offerView = row
        // Room for the offer, so the paper keeps its size.
        var frame = window.frame
        frame.size.height += 46
        frame.origin.y -= 46
        window.setFrame(frame, display: true)
    }

    @objc private func useClipboard() {
        guard let textView else { return }
        hideOffer()
        textView.pasteFromClipboard()
        window?.makeFirstResponder(textView)
    }

    @objc private func dismissOffer() {
        hideOffer()
    }

    private func hideOffer() {
        guard let window, let glass = window.contentView, let paperView, let offerView else { return }
        offerView.removeFromSuperview()
        self.offerView = nil
        let top = paperView.topAnchor.constraint(equalTo: glass.topAnchor, constant: 30)
        top.isActive = true
        paperTop = top
        var frame = window.frame
        frame.size.height -= 46
        frame.origin.y += 46
        window.setFrame(frame, display: true, animate: true)
    }

    // MARK: The sheet

    private static let size = NSSize(width: 360, height: 240)

    private func show(_ text: NSAttributedString, editing url: URL?) {
        close()
        editing = url

        let window = EditorPanel(contentRect: NSRect(origin: .zero, size: Self.size),
                                 styleMask: [.titled, .closable, .resizable, .fullSizeContentView, .nonactivatingPanel],
                                 backing: .buffered, defer: false)
        window.titleVisibility = .hidden
        window.titlebarAppearsTransparent = true
        window.isMovableByWindowBackground = true
        window.level = .floating
        window.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        window.hidesOnDeactivate = false
        window.isReleasedWhenClosed = false
        window.minSize = NSSize(width: 260, height: 170)
        window.delegate = self
        window.onDone = { [weak self] in self?.done() }
        window.onCancel = { [weak self] in self?.cancel() }
        window.standardWindowButton(.miniaturizeButton)?.isHidden = true
        window.standardWindowButton(.zoomButton)?.isHidden = true

        // The glass, like the frame of a card on the line.
        let glass = NSVisualEffectView()
        glass.material = .hudWindow
        glass.blendingMode = .behindWindow
        glass.state = .active
        window.contentView = glass

        // The paper, inset in the glass.
        let paper = NSView()
        paper.wantsLayer = true
        paper.layer?.backgroundColor = NoteCard.paper.cgColor
        paper.layer?.cornerRadius = 12
        paper.layer?.cornerCurve = .continuous
        paper.layer?.borderWidth = 0.5
        paper.layer?.borderColor = NSColor.black.withAlphaComponent(0.08).cgColor
        paper.translatesAutoresizingMaskIntoConstraints = false
        glass.addSubview(paper)

        let scroll = NSScrollView()
        scroll.drawsBackground = false
        scroll.hasVerticalScroller = true
        scroll.autohidesScrollers = true
        scroll.translatesAutoresizingMaskIntoConstraints = false
        let textView = NoteTextView(frame: NSRect(origin: .zero, size: Self.size))
        textView.minSize = .zero
        textView.maxSize = NSSize(width: CGFloat.greatestFiniteMagnitude, height: .greatestFiniteMagnitude)
        textView.isVerticallyResizable = true
        textView.isHorizontallyResizable = false
        textView.autoresizingMask = [.width]
        textView.textContainer?.widthTracksTextView = true
        textView.delegate = self
        textView.isRichText = true
        textView.importsGraphics = true
        textView.allowsImageEditing = false
        textView.allowsUndo = true
        textView.drawsBackground = false
        textView.textColor = NoteCard.ink
        textView.insertionPointColor = NoteCard.ink
        textView.textContainerInset = NSSize(width: 8, height: 10)
        textView.isAutomaticQuoteSubstitutionEnabled = false
        textView.isAutomaticDashSubstitutionEnabled = false
        textView.typingAttributes = NoteTextView.inkAttributes
        textView.textStorage?.setAttributedString(NoteTextView.inked(text))
        scroll.documentView = textView
        paper.addSubview(scroll)

        let hint = NSTextField(labelWithString: url == nil
            ? L("⌘↩ hangs it on the line")
            : L("⌘↩ saves it on the line"))
        hint.font = .systemFont(ofSize: 11)
        hint.textColor = .secondaryLabelColor
        hint.lineBreakMode = .byTruncatingTail
        hint.toolTip = L("Paste or drop a screenshot, a picture or any file here")
        hint.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)

        let cancel = NSButton(title: L("Cancel"), target: self, action: #selector(cancelPressed))
        cancel.bezelStyle = .rounded
        cancel.controlSize = .regular
        let done = NSButton(title: url == nil ? L("Hang") : L("Save"), target: self, action: #selector(donePressed))
        done.bezelStyle = .rounded
        done.keyEquivalent = "\r"
        done.keyEquivalentModifierMask = .command

        let bar = NSStackView(views: [hint, cancel, done])
        bar.orientation = .horizontal
        bar.spacing = 8
        bar.setHuggingPriority(.defaultLow, for: .horizontal)
        bar.translatesAutoresizingMaskIntoConstraints = false
        glass.addSubview(bar)

        // The inset matches a card's: 4 points of glass around the paper,
        // a little more under the title bar.
        let top = paper.topAnchor.constraint(equalTo: glass.topAnchor, constant: 30)
        NSLayoutConstraint.activate([
            top,
            paper.leadingAnchor.constraint(equalTo: glass.leadingAnchor, constant: 8),
            paper.trailingAnchor.constraint(equalTo: glass.trailingAnchor, constant: -8),
            paper.bottomAnchor.constraint(equalTo: bar.topAnchor, constant: -8),
            scroll.topAnchor.constraint(equalTo: paper.topAnchor, constant: 2),
            scroll.leadingAnchor.constraint(equalTo: paper.leadingAnchor, constant: 2),
            scroll.trailingAnchor.constraint(equalTo: paper.trailingAnchor, constant: -2),
            scroll.bottomAnchor.constraint(equalTo: paper.bottomAnchor, constant: -2),
            bar.leadingAnchor.constraint(equalTo: glass.leadingAnchor, constant: 14),
            bar.trailingAnchor.constraint(equalTo: glass.trailingAnchor, constant: -10),
            bar.bottomAnchor.constraint(equalTo: glass.bottomAnchor, constant: -10),
        ])

        self.window = window
        self.textView = textView
        self.paperView = paper
        paperTop = top
        place(window)
        window.makeKeyAndOrderFront(nil)
        window.makeFirstResponder(textView)
        textView.fitAttachments()
        textView.setSelectedRange(NSRange(location: textView.textStorage?.length ?? 0, length: 0))
    }

    /// Centred just under where the line hangs, on the screen you are using,
    /// so the note has only a short way to fly.
    private func place(_ window: NSWindow) {
        guard let visible = LinePanel.screenUnderPointer()?.visibleFrame else {
            window.center()
            return
        }
        let size = window.frame.size
        window.setFrameOrigin(NSPoint(x: visible.midX - size.width / 2,
                                      y: visible.maxY - Layout.panelHeight - size.height + 40))
    }

    // MARK: Done and cancel

    @objc private func donePressed() { done() }
    @objc private func cancelPressed() { cancel() }

    private func done() {
        guard let window, let textView, let storage = textView.textStorage else { return }
        let rich = NSAttributedString(attributedString: storage)
        let words = Notes.plainText(of: rich)
        let attached = Notes.hasAttachments(rich)
        let empty = !attached && words.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        guard words.count <= Notes.maxCharacters else {
            NSSound.beep()
            return
        }

        if let url = editing {
            // Emptying a note does not delete it; the cross is for that.
            if !empty { save(rich, words: words, attached: attached, over: url) }
            close()
            return
        }
        guard !empty else {
            draft = NSAttributedString()
            close()
            return
        }
        guard let url = attached ? Notes.create(rich: rich) : Notes.create(words) else {
            NSSound.beep()
            return
        }
        draft = NSAttributedString()
        let from = paperView.map { window.convertToScreen($0.convert($0.bounds, to: nil)) } ?? window.frame
        close()
        onCreated(url, from)
    }

    /// A rich note stays rich. A text note stays text unless something was
    /// pasted into it; then it becomes a rich note in Pinza's folder, and a
    /// text file of Pinza's own goes to the Trash. One from a watched folder
    /// stays where it is, untouched.
    private func save(_ rich: NSAttributedString, words: String, attached: Bool, over url: URL) {
        if Notes.isRich(url) {
            if Notes.write(rich: rich, to: url) { onSaved(url) }
        } else if !attached {
            if Notes.write(words, to: url) { onSaved(url) }
        } else if let new = Notes.create(rich: rich) {
            onReplaced(url, new)
            if url.standardizedFileURL.path.hasPrefix(Notes.folder.standardizedFileURL.path + "/") {
                try? FileManager.default.trashItem(at: url, resultingItemURL: nil)
            }
        } else {
            NSSound.beep()
        }
    }

    /// A new note keeps what was written for next time. An edit is dropped.
    private func cancel() {
        if editing == nil, let storage = textView?.textStorage {
            draft = NSAttributedString(attributedString: storage)
        }
        close()
    }

    private func close() {
        let window = self.window
        self.window = nil
        textView = nil
        paperView = nil
        offerView = nil
        paperTop = nil
        editing = nil
        window?.delegate = nil
        window?.orderOut(nil)
        window?.close()
    }

    // MARK: NSWindowDelegate

    /// The close button counts as cancel.
    func windowShouldClose(_ sender: NSWindow) -> Bool {
        cancel()
        return false
    }

    // MARK: NSTextViewDelegate

    func textView(_ textView: NSTextView, doCommandBy selector: Selector) -> Bool {
        if selector == #selector(NSResponder.cancelOperation(_:)) {
            cancel()
            return true
        }
        return false
    }

    func textDidChange(_ notification: Notification) {
        textView?.fitAttachments()
    }
}

/// What is on the clipboard, in a few words and a small picture, for the
/// offer at the top of the sheet.
struct ClipboardPreview {
    let icon: NSImage
    let summary: String

    @MainActor
    init?(_ pb: NSPasteboard) {
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], let first = urls.first {
            icon = NSWorkspace.shared.icon(forFile: first.path)
            summary = urls.count == 1 ? first.lastPathComponent : String(format: L("%d files"), urls.count)
            return
        }
        let string = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        if string.isEmpty, let image = NSImage(pasteboard: pb), image.size.width > 0 {
            icon = image
            summary = L("A picture")
            return
        }
        guard !string.isEmpty else { return nil }
        icon = NSImage(systemSymbolName: "text.alignleft", accessibilityDescription: nil) ?? NSImage()
        summary = String(string.split(whereSeparator: \.isNewline).first ?? "").prefix(80).description
    }
}

/// The paper's text view. Words pasted in take the note's own ink, so a note
/// reads the same whatever it was copied from. Pictures and files go in as
/// they are, shrunk to fit the sheet.
final class NoteTextView: NSTextView {
    static let inkAttributes: [NSAttributedString.Key: Any] = [
        .font: NSFont.systemFont(ofSize: 14),
        .foregroundColor: NoteCard.ink,
    ]

    /// Text in the note's ink and size, its attachments left alone.
    static func inked(_ text: NSAttributedString) -> NSAttributedString {
        let result = NSMutableAttributedString(attributedString: text)
        result.addAttributes(inkAttributes, range: NSRange(location: 0, length: result.length))
        return result
    }

    private static let richTypes: [NSPasteboard.PasteboardType] = [.fileURL, .png, .tiff, .pdf]

    private func carriesAttachments(_ pb: NSPasteboard) -> Bool {
        pb.availableType(from: Self.richTypes) != nil
    }

    override func paste(_ sender: Any?) {
        pasteFromClipboard()
    }

    /// A screenshot, a picture or a file goes in as an attachment; anything
    /// else as plain words.
    func pasteFromClipboard() {
        let pb = NSPasteboard.general
        if carriesAttachments(pb), !hasOnlyWords(pb) {
            insertAttachments(from: pb)
        } else {
            pasteAsPlainText(nil)
        }
    }

    /// Text copied from a document brings a picture of itself along; the
    /// words are what was meant.
    private func hasOnlyWords(_ pb: NSPasteboard) -> Bool {
        let hasFiles = pb.availableType(from: [.fileURL]) != nil
        let words = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        return !hasFiles && !words.isEmpty
    }

    /// Files are copied into the note, pictures as pictures.
    private func insertAttachments(from pb: NSPasteboard) {
        var pieces: [NSAttributedString] = []
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL] {
            for url in urls.prefix(Intake.maxFiles) {
                guard let wrapper = try? FileWrapper(url: url, options: .immediate) else { continue }
                wrapper.preferredFilename = url.lastPathComponent
                pieces.append(NSAttributedString(attachment: NSTextAttachment(fileWrapper: wrapper)))
            }
        } else if let type = pb.availableType(from: [.png, .tiff, .pdf]), let data = pb.data(forType: type) {
            // Saved as PNG, which every app reads; a PDF stays a PDF.
            let isPDF = type == .pdf
            let bytes = isPDF ? data : (NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) ?? data)
            let wrapper = FileWrapper(regularFileWithContents: bytes)
            wrapper.preferredFilename = isPDF ? "Pasted.pdf" : "Pasted.png"
            pieces.append(NSAttributedString(attachment: NSTextAttachment(fileWrapper: wrapper)))
        }
        guard !pieces.isEmpty else {
            NSSound.beep()
            return
        }
        let insert = NSMutableAttributedString()
        for (n, piece) in pieces.enumerated() {
            if n > 0 { insert.append(NSAttributedString(string: "\n", attributes: Self.inkAttributes)) }
            insert.append(piece)
        }
        let range = selectedRange()
        guard shouldChangeText(in: range, replacementString: insert.string) else { return }
        textStorage?.replaceCharacters(in: range, with: insert)
        didChangeText()
        setSelectedRange(NSRange(location: range.location + insert.length, length: 0))
        typingAttributes = Self.inkAttributes
    }

    /// Pictures shrink to the sheet's width, so a whole screenshot fits.
    /// Files that are not pictures keep their icon.
    func fitAttachments() {
        guard let storage = textStorage else { return }
        let width = max(80, bounds.width - textContainerInset.width * 2 - 12)
        var changed = false
        storage.enumerateAttribute(.attachment, in: NSRange(location: 0, length: storage.length)) { value, _, _ in
            // Sized once; decoding every picture at each key press would show.
            guard let attachment = value as? NSTextAttachment, attachment.bounds.size == .zero,
                  let image = attachment.image
                    ?? attachment.fileWrapper?.regularFileContents.flatMap(NSImage.init(data:)),
                  image.size.width > 0, image.size.height > 0 else { return }
            let scale = min(1, width / image.size.width)
            let size = CGSize(width: (image.size.width * scale).rounded(), height: (image.size.height * scale).rounded())
            if attachment.bounds.size != size {
                attachment.bounds = CGRect(origin: .zero, size: size)
                changed = true
            }
        }
        if changed {
            storage.edited(.editedAttributes, range: NSRange(location: 0, length: storage.length), changeInLength: 0)
            needsDisplay = true
        }
    }
}

/// A floating panel that takes the keyboard without activating the app.
/// With no main menu to carry them, the editing shortcuts are handled here.
final class EditorPanel: NSPanel {
    var onDone: () -> Void = {}
    var onCancel: () -> Void = {}

    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { true }

    override func performKeyEquivalent(with event: NSEvent) -> Bool {
        let flags = event.modifierFlags.intersection([.command, .control, .option, .shift])
        if flags == .command, [kVK_Return, kVK_ANSI_KeypadEnter].contains(Int(event.keyCode)) {
            onDone()
            return true
        }
        if flags == .command, event.charactersIgnoringModifiers?.lowercased() == "w" {
            onCancel()
            return true
        }
        let key = event.charactersIgnoringModifiers?.lowercased() ?? ""
        var action: Selector?
        if flags == .command {
            switch key {
            case "x": action = #selector(NSText.cut(_:))
            case "c": action = #selector(NSText.copy(_:))
            case "v": action = #selector(NSText.paste(_:))
            case "a": action = #selector(NSText.selectAll(_:))
            case "z": action = Selector(("undo:"))
            default: break
            }
        } else if flags == [.command, .shift], key == "z" {
            action = Selector(("redo:"))
        }
        if let action, NSApp.sendAction(action, to: nil, from: self) { return true }
        return super.performKeyEquivalent(with: event)
    }

    override func cancelOperation(_ sender: Any?) {
        onCancel()
    }
}
